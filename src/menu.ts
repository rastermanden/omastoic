// Preserve the user's JSONC byte-for-byte outside our marked block. Match the
// host's intentionally small grammar (whole-line comments and trailing commas).
import { PLUGIN_ID } from "./plugin-id.ts";

export const BEGIN = "// >>> omastoic:begin";
export const END = "// <<< omastoic:end";
export const PARENT = "appearance.branding.screensaver";

export function rows(): string[] {
  const installed = `[[ -f ~/.config/omarchy/plugins/${PLUGIN_ID}/manifest.json ]]`;
  return [
    `  "${PARENT}.stoics": {"icon":"󰁰","label":"Stoics","description":"Rotate cited Stoic quotes on the screensaver","when":"${installed}","checked":"omarchy-toggle-enabled omastoic","action":"omastoic toggle"},`,
  ];
}

const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// v2 owns exactly the newlines it adds; retain compatibility with old blocks.
const currentBlock = new RegExp(`\\n  ${escape(BEGIN)} v2[^\\n]*\\n[\\s\\S]*?  ${escape(END)}\\n`);
const legacyBlock = new RegExp(`(?:\\r?\\n)*[ \\t]*${escape(BEGIN)}[^\\n]*\\n[\\s\\S]*?${escape(END)}[ \\t]*(?=\\r?\\n|$)`);

function parse(source: string): Record<string, unknown> {
  const stripped = source.replace(/^\s*\/\/[^\n]*(\n|$)/gm, "").replace(/,(\s*[}\]])/g, "$1");
  const value = stripped.trim() ? JSON.parse(stripped) : {};
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error("omastoic: menu must be a JSONC object");
  return value;
}

export function withoutBlock(source: string): string {
  const next = source.replace(currentBlock, "");
  return next === source ? source.replace(legacyBlock, "") : next;
}
export function hasBlock(source: string): boolean {
  return currentBlock.test(source) || legacyBlock.test(source);
}

/** Insert FIRST: our trailing comma separates us from any existing last row,
 * without ever having to edit the user's separator or a brace inside a string.
 * Support the host's optional {"items": {...}} envelope too. */
export function withBlock(source: string, lines = rows()): string {
  const clean = withoutBlock(source);
  const value = parse(clean);
  const tokens = [...clean.matchAll(/^\s*\/\/[^\n]*$|"(?:\\.|[^"\\])*"|[{}:[\],]/gm)]
    .filter((m) => !m[0].trimStart().startsWith("//"));
  let open = tokens.find((m) => m[0] === "{")?.index;
  if (value.items && typeof value.items === "object" && !Array.isArray(value.items)) {
    let depth = 0;
    for (let i = 0; i < tokens.length; i++) {
      const token = tokens[i][0];
      if (depth === 1 && token.startsWith('"') && JSON.parse(token) === "items" && tokens[i + 1]?.[0] === ":" && tokens[i + 2]?.[0] === "{") {
        open = tokens[i + 2].index;
        break;
      }
      if (token === "{" || token === "[") depth++;
      if (token === "}" || token === "]") depth--;
    }
  }
  const content = open == null ? ["{", ...lines, "}"] : lines;
  const block = `\n  ${BEGIN} v2 — generated by omastoic setup\n${content.join("\n")}\n  ${END}\n`;
  const offset = open == null ? clean.length : open + 1;
  const next = clean.slice(0, offset) + block + clean.slice(offset);
  parse(next); // Fail closed; callers must never write an invalid menu.
  return next;
}
